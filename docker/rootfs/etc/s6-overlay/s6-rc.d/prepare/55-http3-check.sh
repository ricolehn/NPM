#!/usr/bin/with-contenv bash
# HTTP/3 (QUIC) Pre-flight: UDP Receive Buffer Diagnostic, Capabilities Guard & Transport Tuning
#
# nginx does not size its QUIC sockets itself, so they get net.core.rmem_default;
# rmem_max only caps what a program asks for and changes nothing for nginx. The
# same default applies to Docker's userland proxy (docker-proxy), which relays the
# UDP traffic of clients reaching an IPv4-only container over IPv6. With the
# kernel's 208 KiB default it drops QUIC bursts and HTTP/3 slows to a crawl, while
# TCP through the same proxy is unaffected.
#
# Recommended host-level fix (run as root on the Docker host, not inside the container):
#   sysctl -w net.core.rmem_default=8388608
# The value is shared with the host, so it can be checked from inside the container.

RMEM_DEFAULT=$(cat /proc/sys/net/core/rmem_default 2>/dev/null || echo 0)
RECOMMENDED_BUFFER=8388608

if [ "${RMEM_DEFAULT}" -lt "${RECOMMENDED_BUFFER}" ] && [ "${RMEM_DEFAULT}" -ne 0 ]; then
    echo "⚠️  WARNING: Host default UDP receive buffer (rmem_default=${RMEM_DEFAULT}) is below the"
    echo "⚠️  recommended ${RECOMMENDED_BUFFER} bytes (8 MiB) for HTTP/3 (QUIC). Packet drops may occur"
    echo "⚠️  under sustained QUIC load, badly so when IPv6 clients go through Docker's userland proxy."
    echo "⚠️  Recommended fix on the Docker host (not inside the container):"
    echo "⚠️    sysctl -w net.core.rmem_default=${RECOMMENDED_BUFFER}"
fi

# Capture whether IPv6 was disabled globally by 50-ipv6.sh before we overwrite default.conf
IPV6_DISABLED=0
if grep -q "#listen \[::\]" /etc/nginx/conf.d/default.conf; then
    IPV6_DISABLED=1
fi

# Upstream compilation guard & Operator kill-switch:
# If Nginx lacks HTTP/3 capabilities OR if NPM_HTTP3_DISABLED=1,
# strip the `quic` listen lines from the default.conf server blocks
# to prevent startup failures or unwanted port bindings.
# We defensively cache and restore the original default.conf to ensure
# dynamic toggles work reliably across container restarts without rebuilds.
if [ ! -f /etc/nginx/conf.d/default.conf.orig ]; then
    cp /etc/nginx/conf.d/default.conf /etc/nginx/conf.d/default.conf.orig
fi
cp /etc/nginx/conf.d/default.conf.orig /etc/nginx/conf.d/default.conf

# QUIC transport settings are taken from the server block that owns the UDP socket
# (the default server in default.conf), so per-host directives are silently ignored
# and these have to be set in the http context, which nginx.conf includes from here.
#
# http3_stream_buffer_size is how much unacknowledged data nginx keeps in flight on
# one stream, so it caps every download at size/RTT: nginx's 64k default allows about
# 200 Mbit/s at a 2.5 ms LAN round trip and 25 Mbit/s at 20 ms, while 4m reaches
# gigabit up to about 30 ms. It is also the per-stream upload window, and memory
# nginx may hold for each active stream.
HTTP3_CONF=/etc/nginx/conf.d/include/http3.conf
HTTP3_STREAM_BUFFER_SIZE="${NPM_HTTP3_STREAM_BUFFER_SIZE:-4m}"
if ! echo "${HTTP3_STREAM_BUFFER_SIZE}" | grep -qE '^[1-9][0-9]*[kKmM]?$'; then
    echo "⚠️  WARNING: NPM_HTTP3_STREAM_BUFFER_SIZE='${HTTP3_STREAM_BUFFER_SIZE}' is not a size such as 1m or 512k, using 4m"
    HTTP3_STREAM_BUFFER_SIZE=4m
fi

# Strip QUIC sockets from default.conf if unsupported or globally disabled
if ! nginx -V 2>&1 | grep -q -- "--with-http_v3_module" || [ "${NPM_HTTP3_DISABLED}" = "1" ]; then
    echo "ℹ️  HTTP/3: Stripping QUIC sockets from default.conf (unsupported or globally disabled)"
    sed -i '/quic/d' /etc/nginx/conf.d/default.conf
    # http3_* directives are unknown to an nginx built without the HTTP/3 module
    rm -f "${HTTP3_CONF}"

    # Cascade sanitization down to static configuration directory blocks
    if [ -d /data/nginx/proxy_host ]; then
        echo "ℹ️  HTTP/3: Mass-sanitizing existing proxy host configurations to prevent boot crashes"
        find /data/nginx/proxy_host -name "*.conf" -type f -exec sed -i '/quic/d' {} +
    fi
else
    echo "ℹ️  HTTP/3: Using a stream buffer of ${HTTP3_STREAM_BUFFER_SIZE} (NPM_HTTP3_STREAM_BUFFER_SIZE)"
    {
        echo "# Generated by 55-http3-check.sh on container start, set NPM_HTTP3_STREAM_BUFFER_SIZE to change it."
        echo "http3_stream_buffer_size ${HTTP3_STREAM_BUFFER_SIZE};"
    } > "${HTTP3_CONF}"
    chown "$PUID:$PGID" "${HTTP3_CONF}"
fi

# If IPv6 was disabled globally, ensure IPv6 sockets (including QUIC ones if still active) remain commented out in default.conf
if [ "${IPV6_DISABLED}" = "1" ] || [ "$(is_true "${DISABLE_IPV6:-}")" = '1' ]; then
    echo "ℹ️  IPv6 is disabled globally. Deactivating IPv6 sockets in default.conf..."
    sed -i 's/^[^#]*listen \[::\]/#listen [::]/g' /etc/nginx/conf.d/default.conf
fi
